const { contextBridge, ipcRenderer } = require('electron');

const on = (ch) => (fn) => ipcRenderer.on(ch, (_e, d) => fn(d));

contextBridge.exposeInMainWorld('notch', {
  config: () => ipcRenderer.invoke('config'),
  setPins: (pins) => ipcRenderer.invoke('set-pins', pins),
  shape: (rects) => ipcRenderer.send('shape', rects),
  hold: (h) => ipcRenderer.send('hold', h),
  focusable: (on) => ipcRenderer.send('focusable', on),
  onHover: on('hover'),
  onCollapse: on('collapse'),
  panelOpen: (open) => ipcRenderer.send('panel-open', open),
  native: (cmd) => ipcRenderer.send('native', cmd),
  onNative: on('native'),
  onClaude: on('claude'),
  onClaudeAlert: on('claude-alert'),
  onClaudePending: on('claude-pending'),
  onExpand: on('expand'),
  claudeSessions: () => ipcRenderer.invoke('claude-sessions'),
  claudePending: () => ipcRenderer.invoke('claude-pending'),
  claudeDecide: (id, decision) => ipcRenderer.send('claude-decide', { id, decision }),
  claudeDismiss: (id) => ipcRenderer.send('claude-dismiss', id),
  claudeFocus: (id) => ipcRenderer.send('claude-focus', id),
  todos: () => ipcRenderer.invoke('todos'),
  todoAdd: (t) => ipcRenderer.invoke('todo-add', t),
  todoToggle: (id) => ipcRenderer.invoke('todo-toggle', id),
  todoDelete: (id) => ipcRenderer.invoke('todo-delete', id),
  stats: () => ipcRenderer.invoke('stats'),
  openHome: () => ipcRenderer.invoke('open-home'),
  openFolder: (i) => ipcRenderer.invoke('open-folder', i),
  openUri: (u) => ipcRenderer.invoke('open-uri', u),
  launch: (w) => ipcRenderer.invoke('launch', w),
  power: (a) => ipcRenderer.invoke('power', a),
  powerPlans: () => ipcRenderer.invoke('power-plans'),
  setPowerPlan: (g) => ipcRenderer.invoke('power-plan-set', g),
  themeGet: () => ipcRenderer.invoke('theme-get'),
  themeToggle: () => ipcRenderer.invoke('theme-toggle'),
  fileIcon: (exe) => ipcRenderer.invoke('file-icon', exe),
  contextMenu: () => ipcRenderer.send('context-menu'),
  trayClick: (key, button) => ipcRenderer.send('tray-click', { key, button }),
  claudeAsk: (question, history) => ipcRenderer.invoke('claude-ask', { question, history }),
  onClaudeAskChunk: on('claude-ask-chunk'),
  onLauncher: on('launcher'),
  onLauncherIndex: on('launcher-index'),
  launcherIndex: () => ipcRenderer.invoke('launcher-index'),
  launcherFiles: (q) => ipcRenderer.invoke('launcher-files', q),
  launcherOpen: (it) => ipcRenderer.invoke('launcher-open', it),
  launcherReveal: (p) => ipcRenderer.invoke('launcher-reveal', p),
  log: (...a) => ipcRenderer.send('log', ...a),
});
